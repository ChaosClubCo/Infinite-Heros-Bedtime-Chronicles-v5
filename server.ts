app.post("/api/gemini/video-status", async (req, res) => {
  try {
    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: "operationName is required" });
    }

    const ai = getGeminiClient();
    const op = new GenerateVideosOperation();
    op.name = operationName;

    const updated = await ai.operations.getVideosOperation({ operation: op });

    res.json({
      done: !!updated.done,
      hasError: !!updated.error,
      error: updated.error,
    });
  } catch (error: any) {
    console.error("Video status polling error:", error);
    res.status(500).json({ error: error?.message || "Failed to check video status" });
  }
});

app.post("/api/gemini/video-download", async (req, res) => {
  try {
    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: "operationName is required" });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return res.status(500).json({ error: "GEMINI_API_KEY is not configured" });
    }

    const ai = getGeminiClient();
    const op = new GenerateVideosOperation();
    op.name = operationName;

    const updated = await ai.operations.getVideosOperation({ operation: op });
    const uri = updated.response?.generatedVideos?.[0]?.video?.uri;

    if (!uri) {
      return res.status(404).json({ error: "Video download URI not ready or found" });
    }

    const videoRes = await fetch(uri, {
      headers: { "x-goog-api-key": apiKey },
    });

    if (!videoRes.ok) {
      return res.status(videoRes.status).json({ error: "Failed to download video stream from provider" });
    }

    const arrayBuffer = await videoRes.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);

    res.setHeader("Content-Type", "video/mp4");
    res.setHeader("Content-Length", buffer.length.toString());
    res.send(buffer);
  } catch (error: any) {
    console.error("Video download error:", error);
    res.status(500).json({ error: error?.message || "Failed to download video" });
  }
});

/**
 * 4. AUDIO TRANSCRIPTION
 * Model: gemini-3.5-transcribe
 */
app.post("/api/gemini/transcribe", async (req, res) => {
  try {
    const { audioBase64, mimeType = "audio/webm", prompt } = req.body;
    if (!audioBase64) {
      return res.status(400).json({ error: "Audio base64 data is required" });
    }

    const ai = getGeminiClient();
    const cleanBase64 = audioBase64.replace(/^data:[^;]+;base64,/, "");

    const response = await ai.models.generateContent({
      model: "gemini-3.5-transcribe",
      contents: {
        parts: [
          {
            inlineData: {
              mimeType,
              data: cleanBase64,
            },
          },
          {
            text: prompt || "Transcribe this spoken audio accurately. Output only the transcription without commentary.",
          },
        ],
      },
    });

    const transcript = response.text || "";
    res.json({
      transcript: transcript.trim(),
      modelUsed: "gemini-3.5-transcribe",
    });
  } catch (error: any) {
    console.error("Transcription error:", error);
    res.status(500).json({ error: error?.message || "Failed to transcribe audio" });
  }
});

// Vite middleware & Static Serving
async function start() {
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (_req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Infinite Heroes Server running on http://0.0.0.0:${PORT}`);
  });
}

start();
