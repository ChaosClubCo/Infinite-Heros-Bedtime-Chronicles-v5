export function getVocabularyWordById(id: string): VocabularyWord {
  return VOCABULARY_WORDS.find((w) => w.id === id) || VOCABULARY_WORDS[0];
}

export function findVocabularyWordByText(text: string): VocabularyWord | undefined {
  const lower = text.toLowerCase();
  return VOCABULARY_WORDS.find((w) => lower.includes(w.word.toLowerCase()));
}
